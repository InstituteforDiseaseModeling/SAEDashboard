// Extensions for files generated by the agent and served from /mind/files/.
const GENERATED_FILE_RE = /\.(png|jpe?g|gif|svg|webp|csv|xlsx?|tsv|json)$/i;

// Normalize a generated-file reference to its served URL. The agent sometimes embeds
// just a bare filename (e.g. "plot.png") instead of the full "/data/tmp/<sid>/plot.png"
// path, which renders broken. Bare filenames point at the current session's tmp dir,
// so resolve them against /mind/files/<sessionId>/.
const makeRewriteFileUrl = (sessionId) => (url) => {
  if (!url) return url;
  const m = url.match(/^\/data\/tmp\/(.+)/);
  if (m) return `/mind/files/${m[1]}`;
  // Bare filename (no path separator, no scheme/leading slash) with a generated-file
  // extension — reconstruct the served path using the current session id.
  if (sessionId && !url.includes('/') && !url.includes(':') && GENERATED_FILE_RE.test(url)) {
    return `/mind/files/${sessionId}/${url}`;
  }
  return url;
};

const makeComponents = (rewriteFileUrl) => ({
  code: ({inline, children, ...props}) => {
    if (inline) return <code style={mdStyles.code} {...props}>{children}</code>;
    return <pre style={mdStyles.pre}><code {...props}>{children}</code></pre>;
  },
  table: ({children}) => <table style={mdStyles.table}>{children}</table>,
  th: ({children}) => <th style={mdStyles.th}>{children}</th>,
  td: ({children}) => <td style={mdStyles.td}>{children}</td>,
  img: ({src, alt}) => <img src={rewriteFileUrl(src)} alt={alt} style={mdStyles.img} />,
  blockquote: ({children}) => <blockquote style={mdStyles.blockquote}>{children}</blockquote>,
  p: ({children}) => <p style={{margin: '4px 0'}}>{children}</p>,
  ul: ({children}) => <ul style={{margin: '4px 0', paddingLeft: 20}}>{children}</ul>,
  ol: ({children}) => <ol style={{margin: '4px 0', paddingLeft: 20}}>{children}</ol>,
  li: ({children}) => <li style={{marginBottom: 2}}>{children}</li>,
  h1: ({children}) => (
    <strong style={{display: 'block', fontSize: '1.1rem', margin: '8px 0 4px'}}>{children}</strong>
  ),
  h2: ({children}) => (
    <strong style={{display: 'block', fontSize: '1.05rem', margin: '6px 0 4px'}}>{children}</strong>
  ),
  h3: ({children}) => (
    <strong style={{display: 'block', fontSize: '1rem', margin: '6px 0 4px'}}>{children}</strong>
  ),
  a: ({href, children}) => {
    const url = rewriteFileUrl(href);
    const isDownload = url && /\.(csv|xlsx?|tsv|json)$/i.test(url);
    return (
      <a href={url} target="_blank" rel="noopener noreferrer" style={{color: '#313A44'}}
        {...(isDownload ? {download: ''} : {})}>
        {children}
      </a>
    );
  },
});

const MarkdownContent = ({content, light, sessionId}) => {
  const wrapperStyle = {
    ...mdStyles.wrapper,
    ...(light ? {color: '#313A44'} : {}),
  };
  const components = React.useMemo(
      () => makeComponents(makeRewriteFileUrl(sessionId)),
      [sessionId],
  );
  return (
    <div style={wrapperStyle}>
      <ReactMarkdown remarkPlugins={[remarkGfm]} components={components}>
        {content || ''}
      </ReactMarkdown>
    </div>
  );
};

MarkdownContent.propTypes = {
  content: PropTypes.string,
  light: PropTypes.bool,
  sessionId: PropTypes.string,
};

export default MarkdownContent;
